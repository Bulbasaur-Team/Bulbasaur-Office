export const SLIDE_IDS = PRESENTATION_SLIDES.map((slide) => slide.id);

export function slideAsset(source: SlideSource, id: string): string {
  if (source === "claude") {
    return `${publicPath("assets/slides/presentation/claude/deck.html")}#${encodeURIComponent(id)}`;
  }
  return publicPath(`assets/slides/presentation/${source}/${id}.svg`);
}

export function slideById(id: string): SlideDef | undefined {
  return PRESENTATION_SLIDES.find((slide) => slide.id === id);
}

/** Слайды «решения» — должны идти после описания проблемы (`pain`). */
export const SOLUTION_SLIDE_IDS: readonly SlideId[] = ["miracle", "cabin", "beach"];

export type ReviewKind =
  | "ok"
  | "no_pain"
  | "no_miracle"
  | "no_beach"
  | "no_ai"
  | "no_tired"
  | "no_market"
  | "has_moat"
  | "has_green"
  | "no_ask"
  | "ask_not_last"
  | "problem_after_solution";

/** Проверка активного набора (только включённые слайды, в текущем порядке). */
export function reviewDeck(ids: string[]): ReviewKind {
  const set = new Set(ids);
  if (!set.has("pain")) return "no_pain";
  if (!set.has("miracle")) return "no_miracle";
  if (!set.has("beach")) return "no_beach";
  if (!set.has("ai")) return "no_ai";
  if (!set.has("tired")) return "no_tired";
  if (!set.has("market")) return "no_market";
  if (set.has("moat")) return "has_moat";
  if (set.has("green")) return "has_green";
  if (!set.has("ask")) return "no_ask";
  if (ids[ids.length - 1] !== "ask") return "ask_not_last";
  const painAt = ids.indexOf("pain");
  const firstSolution = ids.findIndex((id) => (SOLUTION_SLIDE_IDS as readonly string[]).includes(id));
  if (firstSolution >= 0 && painAt > firstSolution) return "problem_after_solution";
  return "ok";
}

