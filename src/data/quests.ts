/** Сравнение фразы Claude: регистр и точки не важны. */
export function matchesClaudePhrase(input: string): boolean {
  const norm = (s: string) =>
    s
      .trim()
      .toLowerCase()
      .replace(/\.+$/g, "")
      .replace(/\s+/g, " ");
  return norm(input) === norm(FRIDGE_QUEST.claudePhrase);
}

/** Ответ коту «ТУДЫ» — без учёта регистра. */
export function matchesCatAnswer(input: string): boolean {
  return input.trim().toUpperCase() === FRIDGE_QUEST.catAnswer;
}

